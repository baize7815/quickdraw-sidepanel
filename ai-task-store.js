(() => {
  'use strict';

  const AI = globalThis.QuickdrawAI;
  const KEY = 'quickdraw_ai_tasks_v1';
  // Keep generated image groups bounded by the existing input-image limit. The
  // task store is the last line of defence for events received from a page.
  const MAX_OUTPUT_IMAGES = Number(AI.MAX_INPUT_IMAGES || 4);
  const configuredMaxTasks = Number(AI.MAX_TASKS);
  const MAX_TASKS = Number.isFinite(configuredMaxTasks) && configuredMaxTasks > 0 ? Math.floor(configuredMaxTasks) : 24;
  const RETAINED_STATUSES = new Set(['ready', 'pending', 'image-ready', 'pending-image']);
  const retainTask = task => !!task && (AI.isActiveTask(task) || RETAINED_STATUSES.has(task.status));
  const limitTasks = tasks => {
    const active = tasks.filter(task => AI.isActiveTask(task));
    const rest = tasks.filter(task => !AI.isActiveTask(task));
    return [...active, ...rest].slice(0, MAX_TASKS);
  };

  function safeTask(task) {
    if (!task || typeof task !== 'object') return null;
    const copy = { ...task };
    copy.prompt = AI.limitText(copy.prompt, AI.MAX_PROMPT_LENGTH);
    copy.rawReply = AI.limitText(copy.rawReply, AI.MAX_REPLY_LENGTH);
    copy.validatedMermaid = AI.limitText(copy.validatedMermaid, AI.MAX_REPLY_LENGTH);
    copy.inputAssetId = String(copy.inputAssetId || '').slice(0, 200);
    const rawInputAssets = Array.isArray(copy.inputAssets) ? copy.inputAssets : (Array.isArray(copy.inputAssetIds) ? copy.inputAssetIds.map((assetId, order) => ({ assetId, order })) : (copy.inputAssetId ? [{ assetId: copy.inputAssetId, order: 0 }] : []));
    copy.inputAssets = rawInputAssets.slice(0, AI.MAX_INPUT_IMAGES || 4).map((item, order) => ({
      assetId: String(item?.assetId || item?.id || '').slice(0, 200),
      order: Number.isFinite(item?.order) ? Number(item.order) : order,
      sourceElementIds: Array.isArray(item?.sourceElementIds) ? item.sourceElementIds.slice(0, 80).map(String) : []
    })).filter(item => item.assetId);
    copy.inputAssetIds = copy.inputAssets.map(item => item.assetId);
    if (!copy.inputAssetId && copy.inputAssetIds.length) copy.inputAssetId = copy.inputAssetIds[0];
    const normalizeOutputImage = (item, order) => {
      if (!item || typeof item !== 'object') return null;
      const assetId = String(item.assetId || item.id || '').slice(0, 200);
      const imageUrl = String(item.imageUrl || item.src || '').slice(0, 2_000);
      const imageType = String(item.imageType || item.type || '').slice(0, 80);
      const imageBytes = Math.max(0, Number(item.imageBytes ?? item.bytes) || 0);
      const imageWidth = Math.max(0, Math.min(16_384, Number(item.imageWidth ?? item.width) || 0));
      const imageHeight = Math.max(0, Math.min(16_384, Number(item.imageHeight ?? item.height) || 0));
      const fingerprint = String(item.fingerprint || item.imageFingerprint || '').slice(0, 240);
      if (!assetId && !imageUrl && !fingerprint) return null;
      return { assetId, imageUrl, imageType, imageBytes, imageWidth, imageHeight, fingerprint, order: Number.isFinite(item.order) ? Number(item.order) : order };
    };
    const rawOutputImages = Array.isArray(copy.outputImages) ? copy.outputImages : [];
    copy.outputImages = rawOutputImages.slice(0, MAX_OUTPUT_IMAGES).map(normalizeOutputImage).filter(Boolean);
    if (!copy.outputImages.length && copy.outputAssetId) {
      const legacy = normalizeOutputImage({
        assetId: copy.outputAssetId, imageUrl: copy.imageUrl, imageType: copy.imageType,
        imageBytes: copy.imageBytes, imageWidth: copy.imageWidth, imageHeight: copy.imageHeight
      }, 0);
      if (legacy) copy.outputImages = [legacy];
    }
    // Persist retry descriptors separately. They intentionally contain URLs
    // and metadata only; generated bytes live in IndexedDB once materialized.
    const rawPendingImages = Array.isArray(copy.pendingImageResults) ? copy.pendingImageResults : [];
    copy.pendingImageResults = rawPendingImages.slice(0, MAX_OUTPUT_IMAGES).map((item, order) => {
      if (!item || typeof item !== 'object') return null;
      const imageUrl = String(item.imageUrl || item.src || '').slice(0, 2_000);
      const imageType = String(item.imageType || item.type || '').slice(0, 80);
      const imageWidth = Math.max(0, Math.min(16_384, Number(item.imageWidth ?? item.width) || 0));
      const imageHeight = Math.max(0, Math.min(16_384, Number(item.imageHeight ?? item.height) || 0));
      const fingerprint = String(item.fingerprint || item.imageFingerprint || '').slice(0, 240);
      const permissionOrigins = (Array.isArray(item.permissionOrigins) ? item.permissionOrigins : (Array.isArray(item.imagePermissionOrigins) ? item.imagePermissionOrigins : [])).slice(0, 4).map(String).filter(origin => /^https:\/\/(?:\*\.)?[a-z0-9.-]+\/\*$/i.test(origin));
      if (!imageUrl && !fingerprint) return null;
      return { imageUrl, imageType, imageWidth, imageHeight, fingerprint, permissionOrigins, order: Number.isFinite(item.order) ? Number(item.order) : order };
    }).filter(Boolean);
    copy.outputAssetId = String(copy.outputAssetId || copy.outputImages[0]?.assetId || '').slice(0, 200);
    copy.imageUrl = String(copy.imageUrl || copy.outputImages[0]?.imageUrl || copy.pendingImageResults[0]?.imageUrl || '').slice(0, 2_000);
    copy.imagePermissionOrigins = (Array.isArray(copy.imagePermissionOrigins) ? copy.imagePermissionOrigins : []).slice(0, 4).map(String).filter(origin => /^https:\/\/(?:\*\.)?[a-z0-9.-]+\/\*$/i.test(origin));
    copy.imageType = String(copy.imageType || '').slice(0, 80);
    copy.imageBytes = Math.max(0, Number(copy.imageBytes) || 0);
    copy.imageWidth = Math.max(0, Math.min(16_384, Number(copy.imageWidth) || 0));
    copy.imageHeight = Math.max(0, Math.min(16_384, Number(copy.imageHeight) || 0));
    copy.stage = String(copy.stage || '').slice(0, 40);
    copy.stageStartedAt = Math.max(0, Number(copy.stageStartedAt) || 0);
    copy.stageDeadlineAt = Math.max(0, Number(copy.stageDeadlineAt) || 0);
    copy.stageLastProgressAt = Math.max(0, Number(copy.stageLastProgressAt) || 0);
    copy.stageToken = String(copy.stageToken || '').slice(0, 120);
    copy.stageProgress = Math.max(0, Math.min(1, Number(copy.stageProgress) || 0));
    copy.pauseReason = String(copy.pauseReason || '').slice(0, 80);
    copy.pausedAt = Math.max(0, Number(copy.pausedAt) || 0);
    copy.tabOwned = copy.tabOwned === true;
    copy.tabOwnerToken = String(copy.tabOwnerToken || '').slice(0, 120);
    copy.tabGroupId = Number.isInteger(copy.tabGroupId) ? copy.tabGroupId : null;
    copy.tabGroupError = String(copy.tabGroupError || '').slice(0, 200);
    copy.sourceElementIds = Array.isArray(copy.sourceElementIds) ? copy.sourceElementIds.slice(0, 80).map(String) : [];
    copy.sourceInputUnits = Array.isArray(copy.sourceInputUnits) ? copy.sourceInputUnits.slice(0, AI.MAX_INPUT_IMAGES || 4).map(unit => Array.isArray(unit) ? unit.slice(0, 80).map(String) : []).filter(unit => unit.length) : [];
    if (copy.sourceBounds && typeof copy.sourceBounds === 'object') copy.sourceBounds = {
      x: Number(copy.sourceBounds.x) || 0, y: Number(copy.sourceBounds.y) || 0,
      w: Math.max(1, Number(copy.sourceBounds.w) || 1), h: Math.max(1, Number(copy.sourceBounds.h) || 1)
    };
    copy.error = AI.limitText(copy.error, 1_000);
    copy.seenEventKeys = Array.isArray(copy.seenEventKeys) ? copy.seenEventKeys.slice(-32).map(String) : [];
    copy.baselineHashes = Array.isArray(copy.baselineHashes) ? copy.baselineHashes.slice(0, 80).map(String) : [];
    copy.requestMessageId = String(copy.requestMessageId || '').slice(0, 240);
    return copy;
  }

  class QuickdrawAITaskStore {
    constructor(key = KEY) {
      this.key = key;
      this.writeQueue = Promise.resolve();
    }

    async readValue() {
      const area = globalThis.chrome?.storage?.local;
      if (area) {
        const result = await area.get(this.key);
        return result?.[this.key];
      }
      try {
        const raw = globalThis.localStorage?.getItem(this.key);
        return raw ? JSON.parse(raw) : undefined;
      } catch {
        return undefined;
      }
    }

    async writeValue(value) {
      const area = globalThis.chrome?.storage?.local;
      if (area) return area.set({ [this.key]: value });
      try { globalThis.localStorage?.setItem(this.key, JSON.stringify(value)); } catch {}
    }

    async list() {
      const value = await this.readValue();
      if (!Array.isArray(value)) return [];
      const retained = value.map(safeTask).filter(retainTask).sort((a, b) => Number(b.updatedAt || 0) - Number(a.updatedAt || 0));
      return limitTasks(retained);
    }

    async pruneHistory() {
      return this.enqueue(async () => {
        const value = await this.readValue();
        if (!Array.isArray(value)) return;
        const retained = value.map(safeTask).filter(retainTask);
        if (retained.length > MAX_TASKS) retained.sort((a, b) => Number(b.updatedAt || 0) - Number(a.updatedAt || 0));
        const limited = limitTasks(retained);
        let changed = limited.length !== value.length;
        if (!changed) {
          try { changed = limited.some((task, index) => JSON.stringify(task) !== JSON.stringify(value[index])); }
          catch { changed = true; }
        }
        if (changed) await this.writeValue(limited);
      });
    }

    async find(taskId) {
      const wanted = String(taskId || '');
      return (await this.list()).find(task => task.taskId === wanted) || null;
    }

    async upsert(task) {
      const value = safeTask(task);
      if (!value?.taskId) throw new Error('AI 任务缺少 taskId。');
      return this.enqueue(async () => {
        const current = await this.list();
        const index = current.findIndex(item => item.taskId === value.taskId);
        if (!retainTask(value)) {
          if (index >= 0) current.splice(index, 1);
        } else if (index >= 0) current[index] = value;
        else current.unshift(value);
        current.sort((a, b) => Number(b.updatedAt || 0) - Number(a.updatedAt || 0));
        const limited = limitTasks(current);
        await this.writeValue(limited);
        return value;
      });
    }

    async update(taskId, patch) {
      const current = await this.find(taskId);
      if (!current) return null;
      const next = safeTask({ ...current, ...patch, taskId: current.taskId, updatedAt: Date.now() });
      return this.upsert(next);
    }

    async remove(taskId) {
      const wanted = String(taskId || '');
      return this.enqueue(async () => {
        const current = await this.list();
        await this.writeValue(current.filter(item => item.taskId !== wanted));
      });
    }

    enqueue(operation) {
      this.writeQueue = this.writeQueue.catch(() => {}).then(operation);
      return this.writeQueue;
    }
  }

  globalThis.QuickdrawAITaskStore = QuickdrawAITaskStore;
  if (typeof module !== 'undefined' && module.exports) module.exports = QuickdrawAITaskStore;
})();
